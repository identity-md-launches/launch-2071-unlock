#!/usr/bin/env python3
"""Pin exact compiler creation code; supplied stage-2 code is hashed before CREATE2.
Build, then --check. Use --write only after reviewing a deliberate source change.
"""
import json, subprocess, sys
from pathlib import Path
root = Path(__file__).resolve().parent.parent
contracts = {'ROUTER':'UnlkSwapRouter','ORACLE':'UnlkOracle','EVIDENCE':'MerkleClaimEvidence','TOKEN':'UnlkToken'}
s = '// SPDX-License-Identifier: MIT\npragma solidity 0.8.26;\n\n// Generated by scripts/generate_code_checks.py from the reviewed build.\nlibrary ReviewedCode {\n'
for label, name in contracts.items():
    a = json.loads((root/'out'/f'{name}.sol'/f'{name}.json').read_text())
    h = subprocess.check_output(['cast','keccak',a['bytecode']['object']],text=True).strip()
    s += f'    bytes32 internal constant {label} = {h};\n'
s += '}\n'
s = subprocess.check_output(['forge','fmt','--raw','-'],input=s,text=True)
p = root/'src/libraries/ReviewedCode.sol'
if '--write' in sys.argv:
    p.write_text(s)
elif p.read_text() != s:
    sys.exit('Reviewed creation hashes differ. Review source changes and regenerate.')
else:
    print('ReviewedCode matches all four compiler creation-code hashes.')
