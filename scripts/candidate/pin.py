#!/usr/bin/env python3
"""Regenerate candidate-only pins after deliberate review; historical pins are immutable here."""
import json,subprocess,sys
from pathlib import Path
contracts={'VERIFIER':'SetupVerifierV2','ROUTER':'UnlkRouterV2','VAULT':'NftFeeVault','ORACLE':'UnlkOracle','EVIDENCE':'MerkleClaimEvidence','TOKEN':'UnlkToken'}
s='// SPDX-License-Identifier: MIT\npragma solidity 0.8.26;\n\n// Generated by scripts/candidate/pin.py. Candidate pending independent review.\nlibrary ReviewedCodeV2 {\n'
for label,name in contracts.items():
 a=json.loads(Path(f'out/{name}.sol/{name}.json').read_text())
 h=subprocess.check_output(['cast','keccak',a['bytecode']['object']],text=True).strip()
 s+=f'    bytes32 internal constant {label} = {h};\n'
s+='}\n'
s=subprocess.check_output(['forge','fmt','--raw','-'],input=s,text=True)
p=Path('src/candidate/ReviewedCodeV2.sol')
if '--write' in sys.argv:p.write_text(s)
elif p.read_text()!=s:raise SystemExit('Candidate creation pins differ')
else:print('Candidate creation pins match')
